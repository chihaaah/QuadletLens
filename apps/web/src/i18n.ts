export type MessageKey = keyof Messages;
export interface Notice {
  key: MessageKey;
  values?: Record<string, string | number>;
}
export function translate(
  language: Language,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  return (language === "ja" ? ja : en)[key].replace(
    /\{(\w+)\}/g,
    (match, name: string) => String(values[name] ?? match),
  );
}
